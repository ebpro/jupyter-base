#!/bin/bash
# set -euo pipefail

# Colors for output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# Configuration
VERSIONS_DIR="${PWD}/versions/generators"

# Logging functions
log_info() { echo -e "${GREEN}INFO: $1${NC}" >&2; }
log_warn() { echo -e "${YELLOW}WARN: $1${NC}" >&2; }
log_error() { echo -e "${RED}ERROR: $1${NC}" >&2; }

# Print header
echo "# Development Environment Versions"
echo
echo "Generated on: $(date '+%Y-%m-%d %H:%M:%S')"
echo

# Execute each generator script

echo "Executing version generator scripts in ${VERSIONS_DIR}..." >&2
shopt -s nullglob
for script in "${VERSIONS_DIR}"/*.sh; do
    echo "Processing script: ${script}" >&2
    chmod +x "${script}"
    if [[ -x "${script}" ]]; then
        script_name=$(basename "${script}")
        
        # Print section separator
        echo "---"
        echo

        # Execute script and capture output
        if ! output=$("${script}"); then
            log_error "${script_name} failed"
            continue
        fi

        # Print script output
        echo "${output}"
        echo

    fi
done
shopt -u nullglob

# Print footer
echo "---"
echo
echo "Generated by \`generate-versions.sh\`"
